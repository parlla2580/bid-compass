-- ---------------------------------------------------------
-- 1. notices — 공고
--    지금은 앱 목데이터 16건을 넣고, API 수집 배치 단계에서 채웁니다.
--    누구나 읽을 수 있고, 쓰기는 서버 배치(secret 키)만 합니다.
-- ---------------------------------------------------------
create table if not exists public.notices (
  id                  bigint generated by default as identity primary key,
  bid_no              text not null,                       -- 공고번호
  bid_ord             text not null default '00',          -- 차수
  title               text not null,                       -- 공고명
  org                 text not null,                       -- 발주기관
  org_type            text not null check (org_type in ('국가기관', '지방자치단체', '공기업·준정부기관')),
  bid_type            text not null check (bid_type in ('물품', '용역', '공사')),
  contract            text not null check (contract in ('일반경쟁', '제한경쟁', '지명경쟁', '수의계약')),
  award               text not null,                       -- 낙찰방식
  est_price           bigint not null,                     -- 추정가격 (부가가치세 제외)
  base_price          bigint,                              -- 기초금액
  closes_at           timestamptz not null,                -- 입찰 마감일시
  period              text,                                -- 납품·용역·공사 기간
  -- 지역제한: region_parsed=false 이면 공고에서 읽지 못함('확인 필요'),
  --          true 이고 region_limit=null 이면 제한 없음
  region_parsed       boolean not null default true,
  region_limit        text[],
  industry_mid        text,                                -- 요구 업종 (null = 제한 없음)
  industry_leaf       text,
  sme_only            boolean,                             -- 중소기업자 한정 (null = 공고에서 읽지 못함)
  direct_product      text,                                -- 직접생산확인 필요 품목
  license             text,                                -- 요구 면허 (공사)
  url                 text,                                -- 나라장터 원문 URL
  raw                 jsonb,                               -- API 원본 응답
  posted_at           timestamptz not null default now(),  -- 공고 게시일시
  created_at          timestamptz not null default now(),
  unique (bid_no, bid_ord)
);

create index if not exists notices_closes_at_idx on public.notices (closes_at);


-- ---------------------------------------------------------
-- 2. company_profiles — 기업 프로필 (회원 1명당 1행)
--    목록형 항목은 null = 미입력, 빈 배열 = '없음'으로 입력함
-- ---------------------------------------------------------
create table if not exists public.company_profiles (
  user_id             uuid primary key references auth.users (id) on delete cascade,
  industry_big        text,                                -- 업종 대분류
  industry_mid        text,                                -- 업종 중분류
  industry_leaf       text,                                -- 업종 세분류
  location            text,                                -- 소재지 (시도)
  company_size        text check (company_size in ('중소기업', '중견기업', '대기업')),
  licenses            text[],                              -- 보유 면허
  direct_products     text[],                              -- 직접생산확인 품목
  records             text not null default '',            -- 수행실적
  pref_types          text[] not null default array['물품', '용역', '공사'],  -- 관심 사업유형
  pref_orgs           text[] not null default '{}',        -- 선호 발주기관
  price_min           bigint,                              -- 관심 추정가격 범위 (null = 제한 없음)
  price_max           bigint,
  updated_at          timestamptz not null default now()
);


-- ---------------------------------------------------------
-- 3. saved_notices — 저장한 공고
-- ---------------------------------------------------------
create table if not exists public.saved_notices (
  user_id             uuid not null references auth.users (id) on delete cascade,
  notice_id           bigint not null references public.notices (id) on delete cascade,
  saved_at            timestamptz not null default now(),
  primary key (user_id, notice_id)
);


-- ---------------------------------------------------------
-- 4. judgments — 판정 결과
--    판정 엔진을 서버로 옮기는 단계에서 사용합니다. (지금은 앱이 화면에서 계산)
-- ---------------------------------------------------------
create table if not exists public.judgments (
  user_id             uuid not null references auth.users (id) on delete cascade,
  notice_id           bigint not null references public.notices (id) on delete cascade,
  status              text not null check (status in ('eligible', 'check', 'ineligible')),
  reasons             jsonb not null default '[]',
  computed_at         timestamptz not null default now(),
  primary key (user_id, notice_id)
);


-- ---------------------------------------------------------
-- 5. 보안 규칙 (RLS)
--    공고는 누구나 읽기만, 나머지는 본인 데이터만 읽고 쓰기
-- ---------------------------------------------------------
alter table public.notices          enable row level security;
alter table public.company_profiles enable row level security;
alter table public.saved_notices    enable row level security;
alter table public.judgments        enable row level security;

drop policy if exists "공고는 누구나 읽기" on public.notices;
create policy "공고는 누구나 읽기" on public.notices
  for select to anon, authenticated using (true);

drop policy if exists "본인 프로필만" on public.company_profiles;
create policy "본인 프로필만" on public.company_profiles
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "본인 저장 공고만" on public.saved_notices;
create policy "본인 저장 공고만" on public.saved_notices
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "본인 판정만 읽기" on public.judgments;
create policy "본인 판정만 읽기" on public.judgments
  for select to authenticated
  using ((select auth.uid()) = user_id);

grant select on public.notices to anon, authenticated;
grant select, insert, update, delete on public.company_profiles to authenticated;
grant select, insert, delete on public.saved_notices to authenticated;
grant select on public.judgments to authenticated;


