-- ---------------------------------------------------------
-- 1. notices 보완
--    실제 API 값은 기획서의 3종 분류보다 다양하므로 값 제한(check)을 풀고 원래 값을 저장
-- ---------------------------------------------------------
alter table public.notices drop constraint if exists notices_org_type_check;
alter table public.notices drop constraint if exists notices_contract_check;
alter table public.notices alter column org_type drop not null;   -- 공고 API에 기관유형 필드 없음

alter table public.notices add column if not exists source            text not null default 'api';  -- 'api' | 'sample'
alter table public.notices add column if not exists demand_org        text;           -- 수요기관
alter table public.notices add column if not exists reserve_rate_min  numeric;        -- 예비가격 범위 시작율(%) 예: -2
alter table public.notices add column if not exists reserve_rate_max  numeric;        -- 예비가격 범위 종료율(%) 예: +2
alter table public.notices add column if not exists floor_rate        numeric;        -- 낙찰하한율(%)
alter table public.notices add column if not exists region_basis      text;           -- 지역제한 소재지 판단기준
alter table public.notices add column if not exists license_limits    jsonb;          -- 면허제한 [{group, name, code, allowed}]
alter table public.notices add column if not exists product_name      text;           -- 세부품명 (물품)
alter table public.notices add column if not exists collected_at      timestamptz not null default now();

-- 기존 목데이터 16건 표시
-- 목데이터는 API 원본(raw)이 없음
update public.notices set source = 'sample' where raw is null and source = 'api';

create index if not exists notices_posted_at_idx on public.notices (posted_at desc);
create index if not exists notices_source_idx    on public.notices (source);


-- ---------------------------------------------------------
-- 2. contracts — 나라장터 계약 (계약정보서비스)
--    공개 조달 데이터. 업체 실적 자동 채움(사업자번호 검색)을 위해 축적
-- ---------------------------------------------------------
create table if not exists public.contracts (
  id                  text primary key,                    -- 통합계약번호
  bid_type            text,                                -- 물품·용역·공사
  title               text not null,                       -- 계약명
  org                 text,                                -- 계약기관
  org_code            text,
  org_kind            text,                                -- 계약기관 소관구분 (예: 교육기관)
  method              text,                                -- 계약체결방법 (예: 수의계약)
  base_law            text,                                -- 근거법령 (예: 지방계약법 (제25조제1항5호나목))
  base_detail         text,                                -- 근거 상세 (예: 추정가격 2천만원 이하 물품 또는 용역)
  amount              bigint,                              -- 금차 계약금액
  total_amount        bigint,                              -- 총 계약금액
  contract_date       date,
  notice_no           text,                                -- 관련 공고번호 (있을 때)
  corps               jsonb,                               -- 계약업체 [{name, ceo, bizno, role, share}]
  corp_biznos         text[],                              -- 검색용 사업자등록번호 목록
  detail_url          text,
  raw                 jsonb,
  registered_at       timestamptz,
  collected_at        timestamptz not null default now()
);

create index if not exists contracts_biznos_idx on public.contracts using gin (corp_biznos);
create index if not exists contracts_org_idx    on public.contracts (org);
create index if not exists contracts_date_idx   on public.contracts (contract_date desc);

alter table public.contracts enable row level security;
drop policy if exists "계약은 누구나 읽기" on public.contracts;
create policy "계약은 누구나 읽기" on public.contracts
  for select to anon, authenticated using (true);
grant select on public.contracts to anon, authenticated;


-- ---------------------------------------------------------
-- 3. collect_runs — 수집 실행 기록 (성공·실패 확인용)
-- ---------------------------------------------------------
create table if not exists public.collect_runs (
  id                  bigint generated by default as identity primary key,
  started_at          timestamptz not null default now(),
  finished_at         timestamptz,
  window_from         timestamptz,
  window_to           timestamptz,
  status              text not null default 'running',     -- running | ok | partial | failed
  notices_upserted    int default 0,
  contracts_upserted  int default 0,
  api_calls           int default 0,
  message             text
);

alter table public.collect_runs enable row level security;
drop policy if exists "수집 기록은 누구나 읽기" on public.collect_runs;
create policy "수집 기록은 누구나 읽기" on public.collect_runs
  for select to anon, authenticated using (true);
grant select on public.collect_runs to anon, authenticated;
